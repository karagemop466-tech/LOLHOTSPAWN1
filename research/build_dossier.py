#!/usr/bin/env python3
"""Render the source-acquisition dossier from the machine-recorded probe receipts.

Every row in the generated markdown is read straight out of a committed JSON receipt
(`data/source_probes.json`, `research/probe_deep.json`, `research/market_ceiling.json`,
`research/bovada_full.json`). Nothing is typed in by hand, so the document cannot drift
from the evidence. Run: python3 research/build_dossier.py
"""
from __future__ import annotations

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "research", "SOURCES.md")


def load(path: str):
    p = os.path.join(ROOT, path)
    if not os.path.exists(p):
        return None
    with open(p, encoding="utf-8") as fh:
        return json.load(fh)


# Short, evidence-derived descriptions for sources whose role is not "price feed".
ROLE_NOTES = {
    "Leaguepedia Cargo": "community-maintained results/wiki API — series history, not prices",
    "Hotspawn fixtures API": "match inventory only — never a probability input",
    "Odds-API.io sports index": "free sports index; its LoL/events endpoints returned HTTP 502 on the deep probe",
    "gol.gg": "community match stats (HTML), no machine-readable price feed",
    "Oracle's Elixir": "community dataset; blocked by bot protection from the runner",
    "Polymarket (gamma)": "prediction-market prices (full-series match markets only)",
    "Pinnacle (guest API)": "sharp bookmaker moneylines (de-vigged)",
    "Kalshi (CFTC)": "regulated event-contract book (de-vigged)",
    "Bovada": "esportsbook decimal moneylines (de-vigged)",
}


def esc(value) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ")


def main() -> None:
    stage1 = load("data/source_probes.json") or {}
    deep = load("research/probe_deep.json") or {}
    ceiling = load("research/market_ceiling.json") or {}
    bovada = load("research/bovada_full.json") or {}

    lines: list[str] = []
    lines.append("# External League of Legends line sources — acquisition dossier")
    lines.append("")
    lines.append("This file is generated by `research/build_dossier.py` from the JSON receipts "
                 "listed at the bottom. It records what was actually tried, what answered, and "
                 "what that means for pricing a match. No source is described as usable unless a "
                 "receipt shows a payload we can parse.")
    lines.append("")

    # ---- stage 1
    if stage1:
        lines.append("## 1. Reachability probe (GitHub Actions `ubuntu-latest`)")
        lines.append("")
        lines.append(f"Probe run: **{esc(stage1.get('checked_utc'))}** · "
                     f"{len(stage1.get('results', []))} endpoints · "
                     f"{sum(1 for r in stage1.get('results', []) if r.get('ok'))} returned HTTP 200.")
        lines.append("")
        lines.append("| Source | Category | HTTP | Payload | Bytes | Verdict |")
        lines.append("|---|---|---|---|---|---|")
        for r in stage1.get("results", []):
            ok = r.get("ok")
            kind = r.get("kind")
            if r.get("name") in ROLE_NOTES:
                verdict = ROLE_NOTES[r["name"]]
            elif ok and kind == "json":
                verdict = "usable machine-readable feed (see §3 for what it prices)"
            elif ok and kind == "html":
                verdict = "reachable, but HTML only — prices render client-side (see §2)"
            elif ok:
                verdict = f"reachable, payload classified `{kind}`"
            else:
                verdict = f"not usable from the runner (`{kind}`)"
            lines.append(f"| {esc(r.get('name'))} | {esc(r.get('category'))} | {r.get('status')} | "
                         f"`{esc(kind)}` | {r.get('bytes'):,} | {esc(verdict)} |")
        lines.append("")

    # ---- stage 2
    if deep:
        lines.append("## 2. Do the reachable HTML pages embed usable prices?")
        lines.append("")
        lines.append(f"Deep probe run: **{esc(deep.get('checked_utc'))}**. Each page below answered "
                     "HTTP 200 but had to be checked for a server-rendered or hydration-time price "
                     "blob (`__NEXT_DATA__`, `__NUXT__`, `__APOLLO_STATE__`, JSON-LD).")
        lines.append("")
        lines.append("| Page | HTTP | Bytes | Embedded JSON found | Odds-like tokens | Verdict |")
        lines.append("|---|---|---|---|---|---|")
        for e in deep.get("evidence", []):
            if e.get("kind") != "page":
                continue
            blobs = ", ".join(b["label"] for b in e.get("embedded_json") or []) or "none"
            tok = e.get("tokens") or {}
            if e.get("status") != 200:
                verdict = "page did not resolve for LoL — nothing to parse"
            elif blobs != "none" and (tok.get("has_odds_word", 0) > 0
                                      or tok.get("has_price_word", 0) > 0):
                verdict = "hydration blob present — needs a per-venue parser (not integrated)"
            else:
                verdict = "no embedded prices; JavaScript-only rendering"
            lines.append(f"| {esc(e.get('name'))} | {e.get('status')} | {e.get('bytes'):,} | "
                         f"{esc(blobs)} | odds={tok.get('has_odds_word', 0)}, "
                         f"decimal={tok.get('has_decimal_word', 0)}, "
                         f"price={tok.get('has_price_word', 0)} | {esc(verdict)} |")
        lines.append("")
        lines.append("| JSON endpoint candidate | HTTP | Parses as JSON | Top-level keys / note |")
        lines.append("|---|---|---|---|")
        for e in deep.get("evidence", []):
            if e.get("kind") != "api":
                continue
            note = ", ".join(e.get("top_level_keys") or []) or esc(str(e.get("fingerprint", ""))[:90])
            lines.append(f"| {esc(e.get('name'))} | {e.get('status')} | "
                         f"{'yes' if e.get('json') else 'no'} | {note} |")
        lines.append("")

    # ---- ceiling
    if ceiling:
        pin = ceiling.get("pinnacle") or {}
        leagues = pin.get("leagues") or []
        priced = sum(l.get("priced_moneylines", 0) for l in leagues)
        lines.append("## 3. The external-market ceiling for League of Legends")
        lines.append("")
        lines.append(f"Measured **{esc(ceiling.get('checked_utc'))}** by enumerating every LoL league "
                     "on Pinnacle's guest API and the full Kalshi and Polymarket LoL inventory.")
        lines.append("")
        lines.append("| Venue | Inventory observed | Two-sided match-winner prices |")
        lines.append("|---|---|---|")
        lines.append(f"| Pinnacle | {len(leagues)} LoL league(s): "
                     f"{esc('; '.join(str(l.get('name')) for l in leagues))} | **{priced}** |")
        lines.append(f"| Kalshi (KXLOLGAME) | {ceiling.get('kalshi', {}).get('event_count', 0)} open events | "
                     f"{ceiling.get('kalshi', {}).get('event_count', 0)} |")
        pm = ceiling.get("polymarket") or {}
        live = 0
        for m in pm.get("markets") or []:
            try:
                prices = [float(x) for x in json.loads(m.get("prices") or "[]")]
            except Exception:  # noqa: BLE001
                continue
            if prices and all(0.01 <= x <= 0.99 for x in prices):
                live += 1
        lines.append(f"| Polymarket | {pm.get('match_market_count', 0)} "
                     f"match-level markets listed (many already settled/illiquid) | "
                     f"**{live}** unsettled two-sided markets |")
        lines.append("")
        for lg in leagues:
            lines.append(f"- **{esc(lg.get('name'))}** — {lg.get('matchups_returned')} matchup objects "
                         f"returned, of which **{lg.get('priced_moneylines')}** carry an open, two-sided "
                         "match-winner moneyline. Pinnacle also lists a separate `(Kills)` market family; "
                         "those are kill totals, not match-winner prices, and are excluded everywhere.")
        lines.append("")
        lines.append("Pinnacle's 138 matchup objects for Worlds include per-game and prop markets; only the "
                     "8 series-level moneylines (plus the 8 `(Kills)` counterparts) are series prices. "
                     "This is why the market-backed share of a 241-match Hotspawn list is small and why the "
                     "rest must be originated.")
        lines.append("")

    # ---- bovada
    if bovada:
        feeds = bovada.get("feeds") or {}
        lines.append("## 4. Bovada coupon breadth check")
        lines.append("")
        lines.append(f"Checked **{esc(bovada.get('checked_utc'))}**.")
        lines.append("")
        lines.append("| Coupon variant | HTTP | Events | Moneylines |")
        lines.append("|---|---|---|---|")
        for name, f in feeds.items():
            lines.append(f"| {esc(name)} | {f.get('status')} | {f.get('events')} | {f.get('moneylines')} |")
        lines.append("")
        lines.append(f"Unique match moneylines across all variants: **{len(bovada.get('moneylines') or [])}**. "
                     "The unfiltered coupon is ~19× larger but contains no additional LoL match moneylines, "
                     "so the production collector keeps the filtered feed.")
        lines.append("")

    lines.append("## 5. What this means for the site")
    lines.append("")
    lines.append("- Market-backed rows use only de-vigged, two-sided prices from venues that returned "
                 "HTTP 200 JSON on the run (`Pinnacle`, `Polymarket`, `Kalshi`, `Bovada`).")
    lines.append("- Venues that block the runner (403 region, bot challenge), or that only serve prices "
                 "after client-side JavaScript runs, are recorded as unverified and are **not** used. "
                 "They are listed on Sources so the gap is visible rather than silently filled.")
    lines.append("- Every remaining match is originated by our own Elo line from Leaguepedia series "
                 "history, with decay, shrinkage and explicit confidence labels.")
    lines.append("- Matches whose participants were formally removed mid-split (`dqteams`) are quarantined "
                 "in the Unresolved section with the settlement basis spelled out, never given an "
                 "invented probability.")
    lines.append("")
    lines.append("## 6. Receipts")
    lines.append("")
    for path, doc in (("data/source_probes.json", stage1), ("research/probe_deep.json", deep),
                      ("research/market_ceiling.json", ceiling), ("research/bovada_full.json", bovada)):
        if doc:
            lines.append(f"- `{path}` — generated {esc(doc.get('checked_utc'))}")
    lines.append("")
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {OUT} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
